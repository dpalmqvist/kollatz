#!/usr/bin/env python3
"""Residue-class certificate for the depth-k 3x+1 preimage count (lower bound).

Classes are the residues c mod M = 3^r with c % 3 != 0.  For a vector v on them put

    Phi(v)(c) = v(2c mod M) + beta(c) * min_{u=0,1,2} v(lift_u(c)),
    beta(c)   = [c % 9 in {2, 8}],
    lift_u(c) = ((2c - 1)/3 + u * 3^(r-1)) mod M      (only used when beta(c) = 1, so c % 3 = 2).

A certificate is (r, P, Q, V) with V a positive integer vector and Q * Phi(V)(c) >= P * V(c) for every
class.  It is found by power iteration in float64 (numpy), rounded to integers, and then checked
exactly with Python integers (no floating point in the check).  Output: cert_r{r}.json and the Lean data
module Generated/CertR{r}.lean.

Usage: python gen_cert.py r [--Q 10000000] [--bits 30] [--iters 100000] [--margin 0]
"""
import argparse
import gzip
import json
import hashlib
import os
import sys
import time

import numpy as np


def structure(r):
    M = 3 ** r
    c = np.arange(M, dtype=np.int64)
    two = (2 * c) % M
    beta = ((c % 9) == 2) | ((c % 9) == 8)
    base = np.where(beta, (2 * c - 1) // 3, 0)
    lifts = np.stack([(base + u * 3 ** (r - 1)) % M for u in range(3)])
    cls = (c % 3) != 0
    return M, two, beta, lifts, cls


def phi(v, two, beta, lifts):
    return v[two] + np.where(beta, np.minimum(np.minimum(v[lifts[0]], v[lifts[1]]), v[lifts[2]]), 0.0)


def power(r, iters, tol=1e-15, verbose=True):
    M, two, beta, lifts, cls = structure(r)
    v = np.where(cls, 1.0, 0.0)
    lo = hi = None
    for it in range(iters):
        w = phi(v, two, beta, lifts)
        ratio = w[cls] / v[cls]
        lo, hi = ratio.min(), ratio.max()
        # averaged step v <- v + Phi(v)/mu: same eigenvector, kills periodic oscillation
        mu = 0.5 * (lo + hi)
        v = v + w / mu
        v = np.where(cls, v / v[cls].max(), 0.0)
        if hi - lo < tol:
            break
        if verbose and it % 2000 == 0:
            print(f"  it {it}: lo {lo:.12f} hi {hi:.12f} gap {hi - lo:.2e}", flush=True)
    return v, lo, hi, it


def phi_exact(V, r):
    """Phi(V) with Python integers; V is a list indexed by residue (entries at multiples of 3 unused)."""
    M = 3 ** r
    t = 3 ** (r - 1)
    out = [0] * M
    for c in range(M):
        if c % 3 == 0:
            continue
        s = V[(2 * c) % M]
        if c % 9 in (2, 8):
            b = (2 * c - 1) // 3
            s += min(V[(b + u * t) % M] for u in range(3))
        out[c] = s
    return out


def check_exact(V, r, P, Q):
    M = 3 ** r
    ph = phi_exact(V, r)
    bad = [c for c in range(M) if c % 3 and not (P * V[c] <= Q * ph[c])]
    pos = all(V[c] > 0 for c in range(M) if c % 3)
    return (not bad) and pos, bad


def tern_defs(vals, r, prefix, base, d, L, out):
    """Append to `out` the defs of the ternary-trie subtree (base, d): it holds the residues base + 3^(r-d)·t,
    t < 3^d (base-3 digits, least significant first).  Each def spells out at most L levels (the elaborator's
    nesting limit) and refers to named subtrees below; subtrees containing only multiples of 3 are `.leaf 0`
    (V is never consulted there).  Children are emitted before their parent."""
    stride = 3 ** (r - d)
    levels = d % L or L
    rest = d - levels

    def nm(b, dd):
        return prefix if dd == r else f"{prefix}_{dd}_{b}"

    def build(b, s, e):
        if s > 1 and b % 3 == 0:
            return "(.leaf 0)"
        if e == 0:
            return f"(.leaf {vals[b]})" if rest == 0 else nm(b, rest)
        return f"(.node {build(b, 3 * s, e - 1)} {build(b + s, 3 * s, e - 1)} {build(b + 2 * s, 3 * s, e - 1)})"

    if rest > 0:
        s2 = stride * 3 ** levels
        for t in range(3 ** levels):
            b = base + stride * t
            if not (s2 > 1 and b % 3 == 0):
                tern_defs(vals, r, prefix, b, rest, L, out)
    out.append(f"noncomputable def {nm(base, d)} : VTree :=\n  {build(base, stride, levels)}\n")


HEADER = "-- generated by gen_cert.py from certs/cert_r{r}.json; do not edit\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def emit_lean(cert, outdir, L=5, part_depth=10, chunk_pow=8, group=27):
    """Write the Lean modules for a certificate:
    Generated/R{r}/Part{i}.lean  data (subtrees of depth part_depth, when r > part_depth)
    Generated/CertR{r}.lean      the trie vtreeR{r} and fR{r} = classOk M t P Q Vmin Vmax vtreeR{r}.get
    Generated/R{r}/Chunks{g}.lean  `allRange fR{r} S (j·S) = true` by `decide +kernel`, S = 3^chunk_pow
    R{r}.lean                    chains the chunks and states the main theorems."""
    r, P, Q, Vmin, Vmax, V = (cert[x] for x in ("r", "P", "Q", "Vmin", "Vmax", "V"))
    cn, cd = cert["c_num"], cert["c_den"]
    M, t = 3 ** r, 3 ** (r - 1)
    gen = os.path.join(outdir, "PreimageBound", "Generated")
    prefix = f"vtreeR{r}"
    imports = ["PreimageBound.Kernel"]
    root_defs = []
    if r > part_depth:
        p = r - part_depth
        parts = [b for b in range(3 ** p) if b % 3 != 0]
        for i, b in enumerate(parts):
            out = []
            tern_defs(V, r, prefix, b, part_depth, L, out)
            mod = f"PreimageBound.Generated.R{r}.Part{i}"
            write(os.path.join(gen, f"R{r}", f"Part{i}.lean"),
                  HEADER.format(r=r) + "import PreimageBound.Kernel\n\nnamespace PreimageBound\n\n" +
                  "\n".join(out) + "\nend PreimageBound\n")
            imports.append(mod)
        # skeleton: the top p levels, leaves are the part roots
        def skel(b, s, e):
            if s > 1 and b % 3 == 0:
                return "(.leaf 0)"
            if e == 0:
                return f"{prefix}_{part_depth}_{b}"
            return f"(.node {skel(b, 3 * s, e - 1)} {skel(b + s, 3 * s, e - 1)} {skel(b + 2 * s, 3 * s, e - 1)})"
        assert p <= 6
        root_defs.append(f"noncomputable def {prefix} : VTree :=\n  {skel(0, 1, p)}\n")
    else:
        tern_defs(V, r, prefix, 0, r, L, root_defs)
    S = 3 ** min(chunk_pow, r)
    J = M // S
    cert_src = (HEADER.format(r=r) + "".join(f"import {m}\n" for m in imports) +
                f"\n/-! Certificate data for r = {r}: V(c) for the {2 * t} classes c mod 3^{r}, c % 3 ≠ 0, in a "
                f"ternary trie.\nP/Q = {P}/{Q}, Vmin = {Vmin}, Vmax = {Vmax}. -/\n\nnamespace PreimageBound\n\n" +
                "\n".join(root_defs) +
                f"\n/-- The per-residue test for the r = {r} certificate. -/\n"
                f"noncomputable def fR{r} : Nat → Bool := classOk {M} {t} {P} {Q} {Vmin} {Vmax} {prefix}.get\n\n"
                "end PreimageBound\n")
    write(os.path.join(gen, f"CertR{r}.lean"), cert_src)
    chunk_mods = []
    for g in range(0, J, group):
        js = range(g, min(J, g + group))
        mod = f"PreimageBound.Generated.R{r}.Chunks{g // group}"
        chunk_mods.append(mod)
        body = "".join(f"theorem chunkR{r}_{j} : allRange fR{r} {S} {j * S} = true := by decide +kernel\n\n"
                       for j in js)
        write(os.path.join(gen, f"R{r}", f"Chunks{g // group}.lean"),
              HEADER.format(r=r) + f"import PreimageBound.Generated.CertR{r}\n\n"
              f"/-! Kernel checks (`decide +kernel`) of residues {g * S} ≤ c < {min(J, g + group) * S}. -/\n\n"
              "namespace PreimageBound\n\n" + body + "end PreimageBound\n")
    cover = [f"theorem covR{r}_1 : ∀ c < {S}, fR{r} c = true := cover_step (cover_zero _) chunkR{r}_0\n"]
    for j in range(1, J):
        cover.append(f"theorem covR{r}_{j + 1} : ∀ c < {(j + 1) * S}, fR{r} c = true := "
                     f"cover_step covR{r}_{j} chunkR{r}_{j}\n")
    thm = THM_TEMPLATE.format(r=r, P=P, Q=Q, Vmin=Vmin, Vmax=Vmax, cn=cn, cd=cd, M=M, t=t, J=J, S=S,
                              ncls=2 * t, mu=f"{P / Q:.7f}",
                              imports="".join(f"import {m}\n" for m in chunk_mods),
                              cover="".join(cover))
    write(os.path.join(outdir, "PreimageBound", f"R{r}.lean"), thm)
    return chunk_mods, J


THM_TEMPLATE = """-- generated by gen_cert.py from certs/cert_r{r}.json; do not edit
import PreimageBound.Check
{imports}
/-! # The certificate for r = {r} ({ncls} classes mod 3^{r}): μ = {P}/{Q} = {mu}, c = {cn}/{cd}

The {J} chunk theorems `chunkR{r}_j : allRange fR{r} {S} (j·{S}) = true` are kernel checks (`decide +kernel`, no
`native_decide`); here they are chained into `certR{r}_ok`. -/

namespace PreimageBound

{cover}
/-- The r = {r} certificate passes `classOk` on every residue below 3^{r}. -/
theorem certR{r}_ok : ∀ c < {M}, classOk {M} {t} {P} {Q} {Vmin} {Vmax} vtreeR{r}.get c = true := covR{r}_{J}

/-- **Lower bound from the r = {r} certificate.** For every `a ≢ 0 (mod 3)` and every `k ≥ 0`, the number of
`n ∈ [1, 2^k a]` with `T^[k] n = a` is at least `({cn}/{cd}) · ({P}/{Q})^k`. -/
theorem preimage_count_lower_bound_R{r} (a : ℕ) (_ha : 0 < a) (ha3 : a % 3 ≠ 0) (k : ℕ) :
    ({cn} / {cd} : ℝ) * ({P} / {Q} : ℝ) ^ k ≤
      ((Finset.Icc 1 (2 ^ k * a)).filter (fun n => T^[k] n = a)).card := by
  have h := lower_bound_of_check (r := {r}) (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by norm_num) certR{r}_ok a ha3 k
  simp only [Nat.cast_ofNat] at h
  have hc : ({cn} / {cd} : ℝ) ≤ {Vmin} / {Vmax} := by norm_num
  exact (mul_le_mul_of_nonneg_right hc (by positivity)).trans h

/-- The same statement with `T` written out, so that it mentions only Mathlib notions. -/
theorem preimage_count_lower_bound_R{r}' (a : ℕ) (ha : 0 < a) (ha3 : a % 3 ≠ 0) (k : ℕ) :
    ({cn} / {cd} : ℝ) * ({P} / {Q} : ℝ) ^ k ≤
      ((Finset.Icc 1 (2 ^ k * a)).filter
        (fun n => (fun m : ℕ => if m % 2 = 0 then m / 2 else (3 * m + 1) / 2)^[k] n = a)).card :=
  preimage_count_lower_bound_R{r} a ha ha3 k

end PreimageBound
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("r", type=int)
    ap.add_argument("--Q", type=int, default=10 ** 7)
    ap.add_argument("--bits", type=int, default=30)
    ap.add_argument("--iters", type=int, default=200000)
    ap.add_argument("--tol", type=float, default=1e-11, help="stop when max - min of Phi(v)/v is below this")
    ap.add_argument("--chunk-pow", type=int, default=8, help="chunk size 3^chunk_pow residues per kernel check")
    ap.add_argument("--group", type=int, default=9, help="chunk theorems per module")
    ap.add_argument("--part-depth", type=int, default=10, help="trie levels per data module")
    ap.add_argument("--cdigits", type=int, default=4, help="decimal digits of the stated constant c")
    ap.add_argument("--from-json", action="store_true",
                    help="reuse certs/cert_r{r}.json (or .json.gz), only emit the Lean modules")
    ap.add_argument("--outdir", default=os.path.dirname(os.path.abspath(__file__)))
    args = ap.parse_args()
    r = args.r
    M = 3 ** r
    js = os.path.join(args.outdir, "certs", f"cert_r{r}.json")
    if args.from_json:
        cert = json.load(gzip.open(js + ".gz", "rt") if not os.path.exists(js) else open(js))
    else:
        t0 = time.time()
        v, lo, hi, it = power(r, args.iters, tol=args.tol)
        print(f"r={r}: power iteration {it + 1} its, {time.time() - t0:.1f} s, mu in [{lo:.12f}, {hi:.12f}]")
        _, two, beta, lifts, cls = structure(r)
        scale = 2.0 ** args.bits
        Vf = np.where(cls, np.floor(v * scale + 0.5), 0.0)
        V = [int(x) for x in Vf]
        ph = phi_exact(V, r)
        Q = args.Q
        P = min((Q * ph[c]) // V[c] for c in range(M) if c % 3)
        ok, bad = check_exact(V, r, P, Q)
        assert ok, bad[:10]
        ok2, _ = check_exact(V, r, P + 1, Q)
        Vmin = min(V[c] for c in range(M) if c % 3)
        Vmax = max(V[c] for c in range(M) if c % 3)
        cden = 10 ** args.cdigits
        cnum = (Vmin * cden) // Vmax
        assert cnum * Vmax <= Vmin * cden
        print(f"  certified mu = P/Q = {P}/{Q} = {P / Q:.7f} (P+1 fails: {not ok2}); Vmin/Vmax = {Vmin}/{Vmax} "
              f"= {Vmin / Vmax:.6f}; stated c = {cnum}/{cden}")
        cert = dict(r=r, M=M, P=P, Q=Q, Vmin=Vmin, Vmax=Vmax, c_num=cnum, c_den=cden,
                    mu_float_lo=float(lo), mu_float_hi=float(hi), V=V)
        os.makedirs(os.path.dirname(js), exist_ok=True)
        with open(js, "w") as f:
            json.dump(cert, f)
        print("  wrote", js, hashlib.sha256(open(js, "rb").read()).hexdigest())
    mods, J = emit_lean(cert, args.outdir, part_depth=args.part_depth, chunk_pow=args.chunk_pow,
                        group=args.group)
    print(f"  Lean: {J} chunks in {len(mods)} module(s):", " ".join(mods))


if __name__ == "__main__":
    main()
